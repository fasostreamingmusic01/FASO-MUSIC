const V="faso-v1",SHELL=["./","index.html","manifest.webmanifest","icon-192.png","icon-512.png"];
self.addEventListener("install",e=>{e.waitUntil(caches.open(V).then(c=>c.addAll(SHELL)).then(()=>self.skipWaiting()))});
self.addEventListener("activate",e=>{e.waitUntil(caches.keys().then(k=>Promise.all(k.filter(x=>x!=V).map(x=>caches.delete(x)))).then(()=>self.clients.claim()))});
self.addEventListener("fetch",e=>{const r=e.request,u=new URL(r.url);
 if(r.method!="GET"||r.headers.has("range"))return;
 const site=u.origin==location.origin,lib=u.hostname=="cdn.jsdelivr.net",img=u.hostname.endsWith("supabase.co")&&u.pathname.includes("/storage/")&&/\.(jpe?g|png|webp)$/i.test(u.pathname);
 if(!(site||lib||img))return;
 e.respondWith(caches.open(V).then(async c=>{const hit=await c.match(r);
  const net=fetch(r).then(x=>{if(x.ok)c.put(r,x.clone());return x}).catch(()=>hit);
  if(hit){e.waitUntil(net);return hit}return net}))});
